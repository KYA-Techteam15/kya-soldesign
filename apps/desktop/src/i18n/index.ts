export const translate = (key: string, lang: Lang): string => {
  const entry = messages[key];
  if (!entry) return key;
  return entry[lang] ?? entry.fr;
};

/** Hook de traduction. `t('ws.section.site')`. */
export const useT = (): ((key: string) => string) => {
  const lang = useUi((s) => s.lang);
  return (key: string) => translate(key, lang);
};

/**
 * Traduction hors composant (gestionnaires, utilitaires appelés lors d'une
 * action) : la langue est lue au moment de l'appel. Dans un rendu, préférer `useT`.
 */
export const tr = (key: string): string => translate(key, useUi.getState().lang);

/** Remplit les jetons {nom} d'un texte traduit : `fill(t(clé), { count: 3 })`. */
export const fill = (text: string, values: Readonly<Record<string, string | number>>): string =>
  text.replace(/\{(\w+)\}/gu, (token, name: string) => (name in values ? String(values[name]) : token));
